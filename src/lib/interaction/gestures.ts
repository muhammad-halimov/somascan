/**
 * Пороги жестов, общие для всего приложения, — как у нативных платформ (Android `ViewConfiguration`, iOS):
 * отличить касание от прокрутки и перетаскивания, удержание — от нажатия, двойное нажатие — от двух одиночных.
 */

/** Палец сдвинулся дальше стольких точек — это прокрутка или перетаскивание, а не касание (дрожание пальца — нет). */
export const TOUCH_SLOP = 10

/** Сколько держать палец, мс, чтобы нажатие стало долгим: как у Android и iOS. */
export const LONG_PRESS_MS = 500

/**
 * Двойное нажатие: второе касание — не позже, чем через столько мс после того, как палец отпустил первое (как
 * у Android). Столько же после отпускания ждёт одиночное нажатие, если у цели есть и двойное: короче — двойное
 * не успеть, длиннее — нажатие кажется неотзывчивым.
 */
export const DOUBLE_TAP_MS = 250

/** Второе касание дальше этого (px) от первого — нажатие в другом месте, а не двойное. */
export const DOUBLE_TAP_SLOP = 48
