/**
 * Числа с единицами, как их пишут на бирках: диаметр (`10 mm`, `Ø12`, `R20`) и вес (`2140 kg`).
 * Общие для показа бирки (`LabelFormatter`) и записи в журнал (`labTableCells`).
 */

/** Диаметр: необязательная пометка (Ø, D, R — гладкий пруток, diam.), число, необязательно `mm`/`мм`. */
const LENGTH = /^\s*(?:[Øø⌀]|d|r|diam\.?)?\s*(\d+(?:[.,]\d+)?)\s*(?:mm|мм)?\s*$/iu

/** Вес: число и необязательно `kg`/`кг`. */
const WEIGHT = /^\s*(\d+(?:[.,]\d+)?)\s*(?:kg|кг)?\s*$/iu

/**
 * Число из значения размера или веса без пометок и единиц (`R20` → `20`, `2140 kg` → `2140`)
 * или `null`, если это не одно число (например, `8/7`).
 */
export function measureNumber(text: string, measure: 'length' | 'weight'): string | null {
  return (measure === 'length' ? LENGTH : WEIGHT).exec(text)?.[1] ?? null
}
