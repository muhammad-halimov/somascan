/**
 * Что возвращает распознавание текста на устройстве (ML Kit на Android, Apple Vision на iOS):
 * строки текста с рамками и содержимое кодов (QR, DataMatrix, штрихкоды). Из этого правила
 * `LabelExtractor` собирают поля бирки.
 */

/** Строка текста, как её прочитал OCR. */
export interface OcrLine {
  /** Текст строки. */
  text: string
  /**
   * Углы рамки строки в пикселях фото, повёрнутого на `OcrPage.rotation`: левый верхний, правый верхний,
   * правый нижний, левый нижний — по очереди x и y (8 чисел). Наклонная строка — наклонная рамка.
   */
  corners: readonly number[]
  /** Уверенность 0…1; `null`, если движок её не сообщает. */
  confidence: number | null
}

/** Текст фото в одном повороте. */
export interface OcrPage {
  /** На сколько градусов по часовой стрелке повёрнуто фото перед чтением: 0, 90, 180 или 270. */
  rotation: number
  /** Ширина повёрнутого фото, px. */
  width: number
  /** Высота повёрнутого фото, px. */
  height: number
  /** Строки в порядке, в каком их отдал движок. */
  lines: OcrLine[]
}

/** Прочитанный код (QR, DataMatrix, штрихкод). */
export interface OcrCode {
  /** Содержимое кода как текст. */
  text: string
  /** Вид кода по названию движка, например `qr` или `VNBarcodeSymbologyQR`. */
  format: string
}
